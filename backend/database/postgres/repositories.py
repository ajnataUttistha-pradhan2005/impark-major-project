"""Durable PostgreSQL ports; physical schema/migrations remain R-005."""

from typing import Protocol
from uuid import UUID

from backend.contracts.actions import ActionRecord, Decision
from backend.contracts.agents import Failure, Observation
from backend.contracts.evidence import Evidence
from backend.state.models import ConversationState
from backend.trace.models import TraceEvent


class SessionRepository(Protocol):
    async def get(self, session_id: UUID) -> ConversationState | None: ...
    async def save(self, state: ConversationState) -> None: ...
    async def history(self, session_id: UUID) -> list[ConversationState]: ...


class DomainRecordRepository(Protocol):
    """Implementation must use explicit transactions and parameterized SQL."""

    async def save_observation(self, observation: Observation) -> None: ...
    async def save_evidence(self, evidence: Evidence) -> None: ...
    async def save_decision(self, decision: Decision) -> None: ...
    async def save_action(self, action: ActionRecord) -> None: ...
    async def save_failure(self, failure: Failure) -> None: ...
    async def write(self, event: TraceEvent) -> None: ...
